import type { DetectedTopic, Need, TopicId } from "./engine/topics";
import type { SafetyResult } from "./engine/safety";
import type { Mask } from "./engine/redact";

export type Reach = "text" | "call" | "in person" | "email";

export interface Person {
  id: string;
  name: string;
  relation: string;
  kind: "person" | "professional";
  goodFor: Need[];
  reach: Reach;
  note: string;
  email?: string;
  phone?: string;
  /** Anything else: an app handle, a contact-form link, office hours. */
  other?: string;
  example?: boolean;
  /** A parent, relative, teacher, coach or counselor the person trusts. Used in 13 to 17 mode. */
  adult?: boolean;
}

export type When = "today" | "week" | "later";

export interface Step {
  id: string;
  text: string;
  when: When;
  personId?: string;
  done: boolean;
  example?: boolean;
}

export type Outcome = "great" | "okay" | "hard" | "not-yet";

export interface FollowUp {
  outcome: Outcome;
  note?: string;
  at: string;
}

export interface Reachout {
  id: string;
  name: string;
  how: Reach;
  at: string; // ISO
  /** Sample rows that exist only to fill the charts; never asked about. */
  example?: boolean;
  followUp?: FollowUp;
  /** "Ask me later" hides the prompt until this time. */
  snoozeUntil?: string;
}

export type NoteAsk = "listen" | "perspective" | "same";

/** A note this person sent to the wild. In this prototype it stays on the device. */
export interface SentNote {
  id: string;
  alias: string;
  text: string;
  ask: NoteAsk;
  at: string;
  replies: NoteReply[];
}

export interface NoteReply {
  id: string;
  text: string;
  at: string;
  alias: string;
  /** "demo" replies are generated by the prototype to show the flow; they are not people. */
  origin: "demo" | "person";
  read: boolean;
}

/** A reply this person wrote to someone else's note. */
export interface MyReply {
  id: string;
  noteId: string;
  excerpt: string;
  text: string;
  at: string;
}

export interface NotesState {
  alias: string;
  sent: SentNote[];
  replies: MyReply[];
  hidden: string[];
  blocked: string[];
  reported: string[];
  /** Notes held back from the wild (they sounded serious) and kept private. */
  private: { id: string; text: string; at: string }[];
}

export interface MyResource {
  id: string;
  name: string;
  how: string;
  note: string;
}

export interface Settings {
  keepHistory: boolean;
  mask: boolean;
  textSize: "regular" | "large";
  theme: "system" | "light" | "dark";
  reduceMotion: boolean;
  milo: boolean;
}

export interface Turn {
  id: string;
  text: string; // already masked when masking is on
  masks: Mask[];
  at: string;
}

export interface Session {
  id: string;
  title: string;
  at: string;
  turns: Turn[];
  topics: DetectedTopic[];
}

/** A link the person saved themselves. Only the link and their own words are kept, never the page's text. */
export interface UserLink {
  id: string;
  url: string;
  host: string;
  title: string;
  note: string;
  topics: TopicId[];
  kind: "experience" | "general" | "professional";
  at: string;
}

/** Age band picked at the start. Only the band is kept, never a birthdate. HEARD is 13 and up. */
export type Age = "teen" | "adult";

export interface Persisted {
  v: 1;
  onboarded: boolean;
  age?: Age;
  settings: Settings;
  people: Person[];
  steps: Step[];
  saved: string[];
  dismissed: string[];
  reachouts: Reachout[];
  history: Session[];
  notes: NotesState;
  myResources: MyResource[];
  links: UserLink[];
}

export interface Thread {
  sessionId?: string;
  turns: Turn[];
  topics: DetectedTopic[];
  removed: TopicId[];
  safety: SafetyResult;
  lastAnalyzedAt: number;
}
